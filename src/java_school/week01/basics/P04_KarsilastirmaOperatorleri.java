package java_school.week01.basics;

public class P04_KarsilastirmaOperatorleri {
    public  static void main(String[] args) {
        int x=10;
        int y=20;
        System.out.println("x y'e eşit mi:" +(x==y));
        System.out.println("x y'ye eit değil mi:" +(x!=y));
        System.out.println("x y'den büyük mü:" +(x>y));
        System.out.println("x y'den küçük mü:" +(x<y));
    }
}